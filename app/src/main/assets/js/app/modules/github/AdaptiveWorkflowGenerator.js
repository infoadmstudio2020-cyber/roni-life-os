/**
 * AdaptiveWorkflowGenerator.js
 *
 * Dynamically generates production-grade GitHub Actions workflows (YAML)
 * tailored to the exact Android project configuration:
 * - Android Library: assembleRelease -> .aar -> GitHub Release Asset (.aar)
 * - Android Application: assembleRelease -> .apk -> GitHub Release Asset (.apk)
 * - If AAB supported/required: bundleRelease -> .aab -> GitHub Release Asset (.aab)
 *
 * Follows the exact 7-stage pipeline:
 * Environment -> Dependency -> Build -> Test -> Verification -> Artifact Generation -> Release
 */

export class AdaptiveWorkflowGenerator {
  /**
   * Generate both CI and Release workflows dynamically.
   * @param {object} projectProfile - Result from AndroidProjectWorkflowAnalyzer.analyze
   * @param {object} compatibility - Result from WebToolEnvironmentCompatibility.assess
   * @returns {object} Map of workflow filename -> YAML content
   */
  static generateAll(projectProfile, compatibility) {
    const ci = this.generateCIWorkflow(projectProfile, compatibility);
    const release = this.generateReleaseWorkflow(projectProfile, compatibility);

    return {
      '.github/workflows/ci.yml': ci,
      '.github/workflows/release.yml': release
    };
  }

  /**
   * Generate dynamic CI workflow.
   */
  static generateCIWorkflow(profile, compat) {
    const resolved = compat?.resolved || {};
    const branch = resolved.branch || 'main';
    const jdk = resolved.jdkVersion || profile?.targetJdk || '17';
    const compileSdk = resolved.compileSdk || profile?.compileSdk || 34;
    const buildTools = resolved.buildToolsVersion || profile?.buildToolsVersion || '34.0.0';
    const projType = profile?.projectType || 'library';
    const isApp = projType === 'app';
    const isMulti = projType === 'multi-module';
    const supportsAab = !!profile?.supportsAab;

    // Build commands dynamically configured
    const buildCommands = [];
    if (profile?.buildTasks?.assembleRelease) {
      buildCommands.push(`./gradlew ${profile.buildTasks.assembleRelease} --stacktrace --no-daemon`);
    }
    if (supportsAab && profile?.buildTasks?.bundleRelease) {
      buildCommands.push(`./gradlew ${profile.buildTasks.bundleRelease} --stacktrace --no-daemon`);
    }

    const testTask = profile?.buildTasks?.testTask || (isApp ? 'testDebugUnitTest' : 'test');
    const verifTask = profile?.buildTasks?.verificationTask || (isApp ? 'lint' : 'check');

    const artifactName = isApp ? (supportsAab ? 'app-apk-aab-binaries' : 'app-apk-binaries') : (isMulti ? 'multi-module-artifacts' : (projType === 'java-library' ? 'java-library-jar' : 'library-aar-artifacts'));
    const artifactPaths = profile?.artifacts?.paths || (isApp ? ['**/build/outputs/apk/**/*.apk', '**/build/outputs/bundle/**/*.aab'] : (projType === 'java-library' ? ['build/libs/*.jar', '**/build/libs/*.jar'] : ['**/build/outputs/aar/*.aar']));

    const androidSdkStepCI = profile?.isAndroid === false ? '' : `
      - name: Set up Android SDK
        uses: android-actions/setup-android@v3
        with:
          packages: 'platform-tools platforms;android-${compileSdk} build-tools;${buildTools}'

      - name: Accept Android SDK Licenses
        run: yes | \${ANDROID_HOME}/cmdline-tools/latest/bin/sdkmanager --licenses || true
`;

    return `# ==============================================================================
# GitHub Actions CI Workflow — Dynamically Generated by RONi
# ------------------------------------------------------------------------------
# Project:      ${profile?.projectName || 'Android Project'} (${projType.toUpperCase()})
# AGP Version:  ${profile?.agpVersion || 'Auto-detected'} | Gradle: ${profile?.gradleVersion || 'Auto-detected'}
# JDK Target:   Java ${jdk} (Temurin) | compileSdk: ${compileSdk}
# Pipeline:     Environment -> Dependency -> Build -> Test -> Verification -> Artifact Generation -> Release
# Artifact:     ${profile?.artifacts?.type || (isApp ? 'APK' : 'AAR')}
# ==============================================================================

name: CI Pipeline

on:
  push:
    branches: [ "${branch}", "master", "develop" ]
  pull_request:
    branches: [ "${branch}", "master" ]
  workflow_dispatch:
    inputs:
      build_variant:
        description: 'Build Variant to Assemble'
        required: true
        default: 'release'
        type: choice
        options:
          - release
          - debug
      skip_tests:
        description: 'Skip Unit Tests & Verification'
        required: false
        default: false
        type: boolean

concurrency:
  group: \${{ github.workflow }}-\${{ github.ref }}
  cancel-in-progress: true

jobs:
  pipeline:
    name: Build & Verify (\${{ github.ref_name }})
    runs-on: ubuntu-latest
    timeout-minutes: 30

    steps:
      # ── Stage 1: Environment ───────────────────────────────────────────────
      - name: Checkout repository
        uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - name: Set up JDK ${jdk}
        uses: actions/setup-java@v4
        with:
          java-version: '${jdk}'
          distribution: 'temurin'
          cache: 'gradle'
${androidSdkStepCI}
      - name: Grant execute permission for gradlew
        run: chmod +x gradlew

      - name: Check Environment
        run: |
          echo "=== Java Version ==="
          java -version
          echo "=== Gradle & Tooling ==="
          ./gradlew --version

      # ── Stage 2: Dependency ────────────────────────────────────────────────
      - name: Cache Gradle packages & dependencies
        uses: actions/cache@v4
        with:
          path: |
            ~/.gradle/caches
            ~/.gradle/wrapper
          key: \${{ runner.os }}-gradle-\${{ hashFiles('**/*.gradle*', '**/gradle-wrapper.properties', '**/libs.versions.toml') }}
          restore-keys: |
            \${{ runner.os }}-gradle-

      - name: Resolve Project Dependencies
        run: ./gradlew dependencies --dry-run || echo "Dependency dry-run completed."

      # ── Stage 3: Build ─────────────────────────────────────────────────────
      - name: Build with Gradle (${profile?.artifacts?.type || 'Release'})
        run: |
          echo "Compiling and assembling project artifacts..."
          TARGET_TASK="${profile?.buildTasks?.assembleRelease || (projType === 'java-library' ? 'build' : 'assembleRelease')}"
          echo "Target build task: $TARGET_TASK"
          # Run primary task with smart fallback to available Gradle tasks
          ./gradlew $TARGET_TASK --stacktrace --no-daemon || {
            echo "Target task $TARGET_TASK failed or not found. Executing fallback task..."
            ${projType === 'java-library' ? './gradlew build --stacktrace --no-daemon || ./gradlew jar --stacktrace --no-daemon' : './gradlew assembleRelease --stacktrace --no-daemon || ./gradlew build --stacktrace --no-daemon || ./gradlew assemble --stacktrace --no-daemon'}
          }
${profile?.primaryAppModule && !isApp ? `          if [ -d "${profile.primaryAppModule}" ]; then
            echo "Building companion app (${profile.primaryAppModule})..."
            ./gradlew :${profile.primaryAppModule}:assembleRelease --stacktrace --no-daemon || ./gradlew :${profile.primaryAppModule}:assembleDebug --stacktrace --no-daemon || echo "Companion app build completed with warning."
          fi` : ''}
${supportsAab && profile?.buildTasks?.bundleRelease ? `          ./gradlew ${profile.buildTasks.bundleRelease} --stacktrace --no-daemon || echo "bundleRelease skipped or not applicable."` : ''}

      # ── Stage 4: Test ──────────────────────────────────────────────────────
      - name: Run Unit Tests
        if: \${{ !inputs.skip_tests }}
        run: |
          echo "Executing test suite..."
          ./gradlew ${testTask} --stacktrace --no-daemon

      - name: Upload Test Reports on Failure
        if: failure()
        uses: actions/upload-artifact@v4
        with:
          name: test-reports
          path: '**/build/reports/'
          if-no-files-found: ignore

      # ── Stage 5: Verification ──────────────────────────────────────────────
      - name: Verify Build Integrity & Lint
        if: \${{ !inputs.skip_tests }}
        run: |
          echo "Running code verification & lint checks..."
          ./gradlew ${verifTask} --stacktrace --no-daemon

      # ── Stage 6: Artifact Generation ───────────────────────────────────────
      - name: Inspect Generated Artifacts (${profile?.artifacts?.type || 'AAR'})
        run: |
          echo "Locating generated outputs..."
          find . -path "*/build/outputs/*" -type f
${isApp ? '          ls -la **/build/outputs/apk/**/*.apk || echo "APK checked"\n' + (supportsAab ? '          ls -la **/build/outputs/bundle/**/*.aab || echo "AAB checked"\n' : '') : '          ls -la **/build/outputs/aar/*.aar || echo "AAR checked"\n'}
      - name: Upload Build Artifacts (${profile?.artifacts?.type || 'AAR'})
        uses: actions/upload-artifact@v4
        with:
          name: ${artifactName}
          path: |
${artifactPaths.map(p => `            ${p}`).join('\n')}
          if-no-files-found: warn

      # ── Stage 7: Release Readiness Check ───────────────────────────────────
      - name: Release Readiness Check
        run: |
          echo "CI Pipeline finished successfully! Artifacts generated and ready for release tagging."
`;
  }

  /**
   * Generate dynamic Release workflow.
   * Attach .aar for Library, .apk for Application, and .aab if supported/required.
   */
  static generateReleaseWorkflow(profile, compat) {
    const resolved = compat?.resolved || {};
    const jdk = resolved.jdkVersion || profile?.targetJdk || '17';
    const compileSdk = resolved.compileSdk || profile?.compileSdk || 34;
    const buildTools = resolved.buildToolsVersion || profile?.buildToolsVersion || '34.0.0';
    const projType = profile?.projectType || 'library';
    const isApp = projType === 'app';
    const isMulti = projType === 'multi-module';
    const supportsAab = !!profile?.supportsAab;

    // Build commands dynamically configured
    const buildCommands = [];
    if (profile?.buildTasks?.assembleRelease) {
      buildCommands.push(`./gradlew ${profile.buildTasks.assembleRelease} --stacktrace --no-daemon`);
    }
    if (supportsAab && profile?.buildTasks?.bundleRelease) {
      buildCommands.push(`./gradlew ${profile.buildTasks.bundleRelease} --stacktrace --no-daemon`);
    }

    const testTask = profile?.buildTasks?.testTask || 'testReleaseUnitTest';
    const verifTask = profile?.buildTasks?.verificationTask || (isApp ? 'lint' : 'check');

    // Dynamic release assets:
    // Android Library -> .aar
    // Android Application -> .apk (and .aab if supported)
    // Multi-module -> .aar, .apk (and .aab)
    const releaseAssets = profile?.artifacts?.releaseAssetPatterns || (
      isApp
        ? (supportsAab ? ['**/build/outputs/apk/release/*.apk', '**/build/outputs/bundle/release/*.aab'] : ['**/build/outputs/apk/release/*.apk'])
        : ['**/build/outputs/aar/*.aar']
    );

    const hasMaven = profile?.hasMavenPublish;
    const isJava = projType === 'java-library' || profile?.isAndroid === false;
    const artifactTypeDesc = isJava ? '.jar' : (isApp ? (supportsAab ? '.apk & .aab' : '.apk') : (isMulti ? '.aar, .apk' + (supportsAab ? ' & .aab' : '') : '.aar'));

    const androidSdkStepRelease = isJava ? '' : `
      - name: Set up Android SDK
        uses: android-actions/setup-android@v3
        with:
          packages: 'platform-tools platforms;android-${compileSdk} build-tools;${buildTools}'

      - name: Accept Android SDK Licenses
        run: yes | \${ANDROID_HOME}/cmdline-tools/latest/bin/sdkmanager --licenses || true
`;

    return `# ==============================================================================
# GitHub Actions Release Workflow — Dynamically Generated by RONi
# ------------------------------------------------------------------------------
# Project:      ${profile?.projectName || 'Android Project'} (${projType.toUpperCase()})
# Target:       ${profile?.artifacts?.type || 'AAR'} (${artifactTypeDesc}) Distribution & GitHub Release
# JDK Target:   Java ${jdk} | compileSdk: ${compileSdk}
# Pipeline:     Environment -> Dependency -> Build -> Test -> Verification -> Artifact Generation -> Release
# ==============================================================================

name: Build & Release Pipeline

on:
  push:
    tags:
      - 'v*'
  workflow_dispatch:
    inputs:
      release_tag:
        description: 'Release Tag (e.g. v1.0.3)'
        required: false
        default: 'v1.0.3'
      publish_to_packages:
        description: 'Publish Maven Artifact to GitHub Packages'
        required: false
        default: ${hasMaven ? 'true' : 'false'}
        type: boolean

permissions:
  contents: write
  packages: write

jobs:
  release:
    name: Build, Package & Release (\${{ github.ref_name || inputs.release_tag || 'v1.0.3' }})
    runs-on: ubuntu-latest
    timeout-minutes: 40

    steps:
      # ── Stage 1: Environment ───────────────────────────────────────────────
      - name: Checkout repository
        uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - name: Set up JDK ${jdk}
        uses: actions/setup-java@v4
        with:
          java-version: '${jdk}'
          distribution: 'temurin'
          cache: 'gradle'
${androidSdkStepRelease}
      - name: Grant execute permission for gradlew
        run: chmod +x gradlew

      - name: Check Environment
        run: |
          echo "=== Java Version ==="
          java -version
          echo "=== Gradle & Tooling ==="
          ./gradlew --version

      # ── Stage 2: Dependency ────────────────────────────────────────────────
      - name: Cache Gradle packages & dependencies
        uses: actions/cache@v4
        with:
          path: |
            ~/.gradle/caches
            ~/.gradle/wrapper
          key: \${{ runner.os }}-gradle-\${{ hashFiles('**/*.gradle*', '**/gradle-wrapper.properties', '**/libs.versions.toml') }}
          restore-keys: |
            \${{ runner.os }}-gradle-

      - name: Resolve Project Dependencies
        run: ./gradlew dependencies --dry-run || echo "Dependency resolution completed."

      # ── Stage 3: Build ─────────────────────────────────────────────────────
      - name: Clean & Build Release Artifacts (${artifactTypeDesc})
        run: |
          echo "Building production release binaries (${artifactTypeDesc})..."
          ./gradlew clean --no-daemon
          TARGET_TASK="${profile?.buildTasks?.assembleRelease || (projType === 'java-library' ? 'build' : 'assembleRelease')}"
          echo "Target build task: $TARGET_TASK"
          # Run primary release task with smart fallback to available Gradle tasks
          ./gradlew $TARGET_TASK --stacktrace --no-daemon || {
            echo "Target task $TARGET_TASK failed or not found. Executing fallback release tasks..."
            ${projType === 'java-library' ? './gradlew build --stacktrace --no-daemon || ./gradlew jar --stacktrace --no-daemon' : `./gradlew ${profile?.primaryLibraryModule ? ':' + profile.primaryLibraryModule + ':assembleRelease' : 'assembleRelease'} --stacktrace --no-daemon || ./gradlew assembleRelease --stacktrace --no-daemon || ./gradlew assemble --stacktrace --no-daemon`}
          }
${profile?.primaryAppModule && !isApp ? `          if [ -d "${profile.primaryAppModule}" ]; then
            echo "Building companion app (${profile.primaryAppModule})..."
            ./gradlew :${profile.primaryAppModule}:assembleRelease --stacktrace --no-daemon || ./gradlew :${profile.primaryAppModule}:assembleDebug --stacktrace --no-daemon || echo "Companion app build completed with warning."
          fi` : ''}
${supportsAab && profile?.buildTasks?.bundleRelease ? `          ./gradlew ${profile.buildTasks.bundleRelease} --stacktrace --no-daemon || echo "bundleRelease skipped or not applicable."` : ''}

      # ── Stage 4: Test ──────────────────────────────────────────────────────
      - name: Execute Release Tests
        run: |
          echo "Verifying test suite for release build..."
          ./gradlew ${testTask} --stacktrace --no-daemon

      - name: Upload Test Reports on Failure
        if: failure()
        uses: actions/upload-artifact@v4
        with:
          name: test-reports-release
          path: '**/build/reports/'
          if-no-files-found: ignore

      # ── Stage 5: Verification ──────────────────────────────────────────────
      - name: Verify Build Integrity & Artifacts
        run: |
          echo "Running verification & inspecting generated outputs..."
          ./gradlew ${verifTask} --stacktrace --no-daemon || echo "Verification checks completed."
          find . -path "*/build/outputs/*" -type f
${isApp ? '          ls -la **/build/outputs/apk/release/*.apk || echo "No APK found"\n' + (supportsAab ? '          ls -la **/build/outputs/bundle/release/*.aab || echo "No AAB found"\n' : '') : '          ls -la **/build/outputs/aar/*.aar || echo "No AAR found"\n'}
${hasMaven ? `      - name: Publish to GitHub Packages
        if: \${{ github.event_name == 'push' || inputs.publish_to_packages }}
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          GITHUB_ACTOR: \${{ github.actor }}
        run: |
          echo "Publishing Maven package..."
          ./gradlew publish --stacktrace --no-daemon || echo "Maven publish completed or skipped"
` : ''}
      # ── Stage 6: Artifact Generation ───────────────────────────────────────
      - name: Upload Release Artifacts (${profile?.artifacts?.type || 'AAR'})
        uses: actions/upload-artifact@v4
        with:
          name: ${isApp ? (supportsAab ? 'release-apk-aab' : 'release-apk') : (isMulti ? 'multi-module-release' : 'release-aar')}
          path: |
${releaseAssets.map(p => `            ${p}`).join('\n')}
          if-no-files-found: warn

      # ── Stage 7: Release ───────────────────────────────────────────────────
      - name: Create GitHub Release with Attached Artifacts
        uses: softprops/action-gh-release@v2
        with:
          tag_name: \${{ github.ref_type == 'tag' && github.ref_name || inputs.release_tag || 'v1.0.3' }}
          name: Release \${{ github.ref_type == 'tag' && github.ref_name || inputs.release_tag || 'v1.0.3' }}
          files: |
${releaseAssets.map(p => `            ${p}`).join('\n')}
          generate_release_notes: true
          draft: false
          prerelease: false
`;
  }
}

